-- Esqueleto mínimo do Supabase + despacho e licoes_robos como estão em produção (22/11/2026), só para a prova local em PGlite.
create role anon nologin; create role authenticated nologin; create role service_role nologin;
create role fake_authenticator login;
grant authenticated to fake_authenticator;
create schema auth;
grant usage on schema public, auth to anon, authenticated, service_role;
create table auth.users (id uuid primary key, email text);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant execute on function auth.uid() to anon, authenticated, service_role;
-- is_admin de teste: admin = quem tem o email de admin de teste
create function public.is_admin() returns boolean language plpgsql stable security definer set search_path to 'public' as $$
declare v_uid uuid := auth.uid(); begin if v_uid is null then return false; end if;
return exists (select 1 from auth.users where id = v_uid and email = 'admin@teste.local'); end $$;

create table public.despacho (
  id bigint generated always as identity primary key,
  origem text not null default 'agente', para text not null, tipo text not null default 'tarefa',
  titulo text not null, tarefa text not null default '', prioridade int not null default 5,
  estado text not null default 'aberta', subtarefas jsonb, resultado text, prova text, conversa_id text,
  custo_estimado numeric, created_at timestamptz not null default now(), iniciada_em timestamptz,
  terminada_em timestamptz, atualizada_em timestamptz not null default now(),
  constraint despacho_estado_check check (estado = any (array['aberta','executando','feita','falhou','a-espera-do-danilo','a-espera-do-pc','cancelada'])),
  constraint despacho_origem_check check (origem = any (array['danilo-telegram','claude-ai','relogio','evento','agente'])),
  constraint despacho_tipo_check check (tipo = any (array['tarefa','campanha','pergunta','ordem-fixa']))
);
create function public.despacho_toca_atualizada() returns trigger language plpgsql as $$ begin new.atualizada_em := now(); return new; end $$;
create trigger despacho_atualizada before update on public.despacho for each row execute function public.despacho_toca_atualizada();

create table public.licoes_robos (
  id bigint generated by default as identity primary key,
  criada_em timestamptz not null default now(), robo text not null, errou text not null, regra text not null,
  origem text not null default 'escriba', vezes integer not null default 1, ativa boolean not null default true,
  arquivada_em timestamptz, arquivada_por text, editada_em timestamptz
);
create table public.agentes_estado (agente text primary key);
