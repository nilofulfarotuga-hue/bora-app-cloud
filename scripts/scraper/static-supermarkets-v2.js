// ─── Main ─────────────────────────────────────────────────────────────────
async function main() {
  const stores = [
    { key: 'pingodoce',   id: 'pingodoce-guarda',   catalog: PINGODOCE_V2 },
    { key: 'intermarche', id: 'intermarche-guarda',  catalog: INTERMARCHE_V2 },
    { key: 'auchan',      id: 'auchan-guarda',       catalog: AUCHAN_V2 },
  ];

  const targets = only ? stores.filter(s => s.key === only) : stores;

  if (targets.length === 0) {
    console.error(`❌ Loja desconhecida: ${only}`);
    process.exit(1);
  }

  const results = [];
  for (const store of targets) {
    console.log(`\n🛒 ${store.id} — ${store.catalog.length} produtos no catálogo V2`);
    const { inserted, skipped, failed } = await insertProducts(store.catalog, store.id);
    results.push({ store: store.id, inserted, skipped, failed });
  }

  console.log('\n─────────────────────────────────────────────');
  console.log('✅ RELATÓRIO V2');
  for (const r of results) {
    console.log(`\n  🏪 ${r.store}`);
    console.log(`     Inseridos: ${r.inserted}  |  Ignorados: ${r.skipped}  |  Falhas: ${r.failed}`);
  }
}

main().catch(err => {
  console.error('❌ Erro fatal:', err.message);
  process.exit(1);
});
