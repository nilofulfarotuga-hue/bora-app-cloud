// ─── Main ─────────────────────────────────────────────────────────────────

async function main() {
  const stores = [
    { key: 'pingodoce',   id: 'pingodoce-guarda',   catalog: PINGODOCE_CATALOG,   target: 1000 },
    { key: 'intermarche', id: 'intermarche-guarda',  catalog: INTERMARCHE_CATALOG, target: 500 },
    { key: 'auchan',      id: 'auchan-guarda',       catalog: AUCHAN_CATALOG,      target: 500 },
  ];

  const targets = only ? stores.filter(s => s.key === only) : stores;

  if (targets.length === 0) {
    console.error(`❌ Loja desconhecida: ${only}. Usa: pingodoce, intermarche, auchan`);
    process.exit(1);
  }

  const results = [];

  for (const store of targets) {
    console.log(`\n🛒 Inserindo produtos — ${store.id}`);
    console.log(`   📦 Catálogo: ${store.catalog.length} produtos preparados`);

    const { inserted, skipped, failed } = await insertProducts(store.catalog, store.id);
    results.push({ store: store.id, inserted, skipped, failed, total: store.catalog.length });
  }

  console.log('\n─────────────────────────────────────────────');
  console.log('✅ RELATÓRIO FINAL');
  for (const r of results) {
    console.log(`\n  🏪 ${r.store}`);
    console.log(`     Catálogo:  ${r.total} produtos`);
    console.log(`     Inseridos: ${r.inserted}`);
    console.log(`     Ignorados: ${r.skipped} (duplicados)`);
    console.log(`     Falhas:    ${r.failed}`);
  }
}

main().catch(err => {
  console.error('❌ Erro fatal:', err.message);
  process.exit(1);
});
